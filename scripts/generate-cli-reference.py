"""Generate/check the CLI reference using help and model-free parameter discovery.

Build the current checkout first. Only --version, --help and parameters --task
are executed on werk; no models, backend installation or inference are needed.
Checked-in output uses the linux-neutral profile. Packaging uses --profile
discovery and a separate --output-dir; with --target, cross-builds compile a
backend-neutral host binary for discovery.
"""

