def cell(value):
    return str(value).replace("|", r"\|").replace("\n", " ")


def code(value):
    return "`" + cell(value) + "`"


def anchor(path):
    return "werk" + ("-" + "-".join(path) if path else "")


def page(path):
    group = path[0] if path else ""
    return f"cli-{group}.md" if group in GROUPS else "cli-options.md"


def command_link(path):
    return f"[{code('werk ' + ' '.join(path))}]({page(path)}#{anchor(path)})"


def parse_help(path, help_text):
    """Keep option declarations separate from descriptions and possible values."""
    help_text = re.sub(r"\[env: ([A-Z0-9_]+)=[^\]]*\]", r"[env: \1]", help_text)
    usage = re.search(r"^Usage: (.+)$", help_text, re.M)
    if not usage:
        raise ValueError(f"Missing usage for {path}")
    sections = defaultdict(list)
    section = "description"
    for line in help_text.splitlines():
        if line in {"Commands:", "Arguments:", "Options:"}:
            section = line[:-1].lower()
        elif line.startswith("Usage:"):
            section = "usage"
        else:
            sections[section].append(line)
    children = []
    for line in sections["commands"]:
        match = re.match(r"^  ([a-z][a-z0-9-]*)\s{2,}", line)
        if match and match[1] != "help":
            children.append(match[1])
    options = []
    current = None
    for line in sections["options"]:
        if re.match(r"^\s+(?:-\w, )?--[a-z]", line):
            parts = re.split(r"\s{2,}", line.strip(), maxsplit=1)
            current = {"syntax": parts[0], "description": parts[1:]}
            current["flag"] = re.search(r"--[a-z][a-z0-9-]*", parts[0])[0]
            options.append(current)
        elif line and not line[0].isspace():
            current = None
            sections["after"].append(line)
        elif current and line.strip():
            current["description"].append(line.strip())
        elif line.strip():
            sections["after"].append(line)
    for option in options:
        option["description"] = " ".join(option["description"])
    if not options:
        raise ValueError(f"No options parsed for {path}")
    return {"path": path, "usage": usage[1], "children": children,
            "description": "\n".join(sections["description"]).strip(),
            "after": "\n".join(sections["after"]).strip(),
            "arguments": "\n".join(sections["arguments"]).strip(), "options": options}


def local_options(node, root):
    # Compare the entire declaration: child flags can shadow global options.
    return [option for option in node["options"]
            if option["flag"] != "--help" and option not in root["options"]]


def table(options, path=()):
    lines = ["| Option | Meaning / parser default |", "| --- | --- |"]
    for option in options:
        note = OPTION_NOTES.get((" ".join(path), option["flag"]), "")
        description = " ".join(filter(None, (note, option["description"])))
        if not description:
            raise ValueError(f"Document the meaning of {' '.join(path)} {option['flag']} in OPTION_NOTES")
        lines.append(f"| {code(option['syntax'])} | {cell(description)} |")
    return lines


def node_intro(node):
    lines = [f"## {'werk ' + ' '.join(node['path'])}".rstrip(), "", node["description"], "",
             "```text", node["usage"], "```", ""]
    if node["children"]:
        lines += ["Subcommands: " + ", ".join(command_link(node["path"] + [c])
                                            for c in node["children"]) + ".", ""]
    if node["arguments"]:
        lines += ["Arguments:", "", "```text", node["arguments"], "```", ""]
    if node["after"]:
        lines += [node["after"], ""]
    return lines


def schema_description(flag, group, schemas):
    """Explain otherwise undocumented parser flags using their public schema."""
    if flag in INPUT_NOTES:
        return INPUT_NOTES[flag]
    positive = "--" + flag.removeprefix("--no-") if flag.startswith("--no-") else flag
    if flag == "--exclude-audio":
        positive = "--include-audio"
    suffix = next((s for s in ("-json", "-file") if positive.endswith(s)), None)
    base = positive.removesuffix(suffix) if suffix else positive
    if base == "--stems":
        base = "--stem"
    candidates = {}
    for descriptors in schemas.values():
        for descriptor in descriptors:
            namespace = descriptor["path"].split(".")[0]
            if namespace not in ({"audio", "tts", "stt", "routing"} if group == "audio" else {group, "routing"}):
                continue
            if descriptor["cli_flag"] == base:
                candidates[descriptor["path"]] = descriptor
    if not candidates:
        raise ValueError(f"Document the meaning of {group} {flag} in INPUT_NOTES")
    parts = []
    for path, descriptor in sorted(candidates.items()):
        desc = descriptor["description"]
        if desc.startswith("Normalized "):
            desc = descriptor["label"] + " (runtime/model-defined control)"
        parts.append(f"{desc}; {descriptor['value_type']} [{code(path)}](parameters-schema.md#{path.split('.')[0]}-parameters)")
    prefix = "Explicitly disable: " if flag != positive else ""
    if suffix:
        prefix += "Load JSON " + ("from a UTF-8 file" if suffix == "-file" else "from the argument") + " for: "
    if any(d["repeatable"] for d in candidates.values()) and not suffix:
        prefix += "Repeatable item for: "
    return prefix + "; ".join(parts) + "."


def render_commands(nodes, schemas, version, profile="linux-neutral"):
    root = nodes[0]
    count_flags = len({o["flag"] for n in nodes for o in n["options"]} - {"--help", "--version"})
    common = [HEADER, "", *PROFILES[profile], "",
              f"Generated from **{version}**. See [CLI semantics](cli.md),",
              "[media input and override rules](cli-media.md), and the",
              "[canonical parameter schema](parameters-schema.md).", ""]
    core = ["# Complete CLI command and option index", "", *common,
            f"Coverage of this profile: **{len(root['children'])} top-level commands**, **{len(nodes)} help nodes**",
            f"(including the root), and **{count_flags} distinct long option names**",
            "(excluding `--help` and `--version`). Compatibility aliases are listed",
            "in [CLI conventions](cli.md#syntax-aliases-and-input-contracts).", "",
            "`<VALUE>` is required; `[VALUE]` is optional; `...` permits multiple values.",
            "Usage lines show required arguments/options. Defaults and accepted enum",
            "values below come from the parser. An absent default means no parser value",
            "is inserted; runtime resolution may still supply one. The built-in",
            "`werk help COMMAND …` and `werk COMMAND … --help` display command help.", "",
            "## Command index", ""]
    core += ["- " + command_link(node["path"]) for node in nodes if node["path"]]
    core += ["", *node_intro(root), "### Global options", "", *table(root["options"]), "",
             "Global options and `--help` are inherited by subcommands unless a local",
             "declaration overrides them. Their backend scope is described in",
             "[Global options](cli.md#global-options).", ""]
    for node in nodes[1:]:
        if node["path"][0] in GROUPS:
            continue
        core += node_intro(node)
        options = local_options(node, root)
        if options:
            core += table(options, node["path"]) + [""]
        core += ["Also accepts the [global options](#global-options).", ""]
    pages = {"cli-options.md": "\n".join(core).rstrip() + "\n"}
    for group in sorted(GROUPS):
        selected = [n for n in nodes if n["path"] and n["path"][0] == group]
        lines = [f"# {group.capitalize()} CLI commands and options", "", *common,
                 "Every command below also accepts [global options](cli-options.md#global-options)",
                 "and `--help`. Each command lists its additional accepted options;",
                 "the catalogue below gives their syntax and meaning. A parsed flag",
                 "does not imply that a particular model/backend implements it.", "",
                 "## Commands", ""]
        lines += ["- " + command_link(n["path"]) for n in selected]
        lines += [""]
        catalogue = defaultdict(list)
        for node in selected:
            lines += node_intro(node)
            options = local_options(node, root)
            if options:
                lines += ["Additional options:", ""]
                for offset in range(0, len(options), 8):
                    lines += ["- " + ", ".join(f"[{code(o['flag'])}](#option-{o['flag'][2:]})"
                                             for o in options[offset:offset + 8])]
                lines += [""]
            for option in options:
                if option not in catalogue[option["flag"]]:
                    catalogue[option["flag"]].append(option)
        lines += ["## Option catalogue", "",
                  "Syntax ending in `...` accepts repeated values. List controls also",
                  "accept repeated occurrences of their flag. Boolean pairs inherit",
                  "when omitted; positive and negative flags conflict. Schema defaults,",
                  "units, types and task applicability are in the linked parameter table.", ""]
        for flag, options in sorted(catalogue.items()):
            lines += [f'<a id="option-{flag[2:]}"></a>', "", f"### {code(flag)}", ""]
            for option in options:
                description = option["description"] or schema_description(flag, group, schemas)
                lines += [code(option["syntax"]), "", description, ""]
        pages[f"cli-{group}.md"] = "\n".join(lines).rstrip() + "\n"
    return pages


def render_schema(schemas, version, profile="linux-neutral"):
    lines = ["# Canonical parameter schema", "", HEADER, "", *PROFILES[profile], "",
             f"Generated from **{version}** for all **{len(schemas)} canonical tasks**.", "",
             "These are task-level schema defaults, before model/family/runtime/profile",
             "resolution. `null` means no concrete schema default. A listed flag is a",
             "schema hint; use the command-specific option reference to check that the",
             "flag exists with that meaning on your command. In particular, global",
             "llama.cpp options can share names with media parameters. Canonical paths",
             "with `werk run … --set PATH=VALUE` avoid that ambiguity.", "",
             "See [parameter resolution and policies](cli-media.md#resolution-and-support)",
             "for precedence, model constraints, support policies and list overrides.",
             "A generic runtime/model-defined control deliberately has no invented",
             "enum or unit: query `werk parameters MODEL --task TASK --json --sources`",
             "for that model's effective contract. Schema acceptance alone does not",
             "promise execution support. The [task table](tasks-and-formats.md) describes",
             "modalities and task names; some tasks use dedicated HTTP endpoints.", ""]
    lines += ["Text generation, image understanding and text-analysis tasks currently",
              "expose only routing descriptors through this generic schema. Their",
              "text sampling and request fields are documented in the [CLI reference](cli.md#text-and-vision-inference)",
              "and [text-analysis API](../api.md#text-analysis-endpoints).", ""]
    rows = defaultdict(lambda: defaultdict(list))
    for task, descriptors in schemas.items():
        for descriptor in descriptors:
            rows[descriptor["path"].split(".")[0]][json.dumps(descriptor, sort_keys=True)].append(task)
    lines += ["Namespaces: " + ", ".join(f"[{n}](#{n}-parameters)" for n in sorted(rows)) + ".", ""]
    for namespace, entries in sorted(rows.items()):
        lines += [f"## {namespace} parameters", "",
                  "| Path / CLI hint | Type / schema default | Constraints / list operations | Meaning / category / impact | Tasks |",
                  "| --- | --- | --- | --- | --- |"]
        for encoded, tasks in sorted(entries.items(), key=lambda item: (json.loads(item[0])["path"], item[0])):
            d = json.loads(encoded)
            constraints = []
            for key in ("minimum", "maximum", "step"):
                if d.get(key) is not None:
                    constraints.append(f"{key}: {code(json.dumps(d[key]))}")
            if d["allowed_values"]:
                constraints.append("values: " + ", ".join(code(json.dumps(v)) for v in d["allowed_values"]))
            if d["repeatable"]:
                constraints.append("repeatable; " + ", ".join(d.get("list_override_operations", [])))
            impact = [name for name in ("memory", "quality", "runtime") if d.get("affects_" + name)]
            description = d["description"]
            if description.startswith("Normalized "):
                description = d["label"] + "; runtime/model-defined control"
            details = f"{description}; category: {d['category']}"
            if d["advanced"]:
                details += "; advanced"
            if impact:
                details += "; affects " + ", ".join(impact)
            applicability = "all tasks" if len(tasks) == len(schemas) else ", ".join(code(t) for t in tasks)
            lines.append(f"| {code(d['path'])}; {code(d['cli_flag'])} | {d['value_type']}; {code(json.dumps(d['default']))} | {'; '.join(constraints) or '—'} | {cell(details)} | {applicability} |")
        lines += [""]
    return "\n".join(lines).rstrip() + "\n"


def generate(binary, store, profile="linux-neutral"):
    # Do not capture a user's credentials, host paths, logging config or env defaults.
    env = {k: v for k, v in os.environ.items()
           if not k.startswith(("WERK_", "HF_", "HUGGING_FACE_"))}
    env.update(NO_COLOR="1", TERM="dumb", COLUMNS="100")

    def run(args):
        result = subprocess.run([str(binary), *args], env=env, capture_output=True,
                                text=True, encoding="utf-8", check=True, timeout=30)
        return result.stdout

    version = run(["--version"]).strip()
    expected = re.search(r'^version = "([^"]+)"', (ROOT / "Cargo.toml").read_text(encoding="utf-8"), re.M)[1]
    if version != "werk " + expected:
        raise ValueError(f"Build this checkout first: expected werk {expected}, got {version}")

    def inspect(path):
        args = list(path)
        if args[:2] == ["runtime", "state"] and len(args) > 2:
            args.insert(2, "STATE_ID")
        return parse_help(path, run([*args, "--help"]))

    nodes, pending = [], [[]]
    with ThreadPoolExecutor(max_workers=6) as pool:
        while pending:
            batch = list(pool.map(inspect, pending))
            nodes.extend(batch)
            pending = [n["path"] + [c] for n in batch for c in n["children"]]
        backend = next(o for o in nodes[0]["options"] if o["flag"] == "--backend")
        if profile == "linux-neutral" and re.search(r"\bburn\b", backend["description"]):
            raise ValueError("--backend burn identifies a noncanonical feature build; rebuild with "
                             "--no-default-features in target/cli-reference-neutral, or use "
                             "--profile discovery with a temporary --output-dir")
        source = (ROOT / "src/capabilities/task.rs").read_text(encoding="utf-8").split("impl InferenceTask", 1)[0]
        tasks = re.findall(r'=> "([a-z-]+)"', source)
        if not tasks:
            raise ValueError("Cannot discover canonical tasks")

        def schema(task):
            data = json.loads(run(["--model-home", str(store), "--no-auto-install-backends",
                                   "parameters", "--task", task, "--json"]))
            return task, data["parameters"]

        schemas = dict(pool.map(schema, tasks))
    pages = render_commands(nodes, schemas, version, profile)
    pages["parameters-schema.md"] = render_schema(schemas, version, profile)
    return pages, nodes, tasks


def discovery_binary(binary, target=None):
    """Use the built artifact natively, or compile a host tool for cross-builds."""
    if target is None:
        return binary.resolve()
    rustc = subprocess.run(["rustc", "-vV"], cwd=ROOT, capture_output=True,
                           text=True, encoding="utf-8", check=True)
    host = re.search(r"^host: (\S+)$", rustc.stdout, re.M)
    if not host:
        raise ValueError("rustc -vV did not report its host target")
    if target == host[1]:
        return binary.resolve()
    print(f"Cross-build for {target}: building CLI reference tool for {host[1]}", flush=True)
    build = subprocess.run(
        ["cargo", "build", "--locked", "--bin", "werk", "--no-default-features",
         "--target", host[1], "--target-dir", str(ROOT / "target/cli-reference-host"),
         "--message-format=json-render-diagnostics"],
        cwd=ROOT, stdout=subprocess.PIPE, text=True, encoding="utf-8", check=True,
    )
    # Cargo reports the executable even for a fresh artifact and respects custom
    # target directories. Do not guess a target/debug path or use werk from PATH.
    executables = []
    for line in build.stdout.splitlines():
        event = json.loads(line)
        if (event.get("reason") == "compiler-artifact"
                and event.get("target", {}).get("name") == "werk"
                and "bin" in event.get("target", {}).get("kind", [])
                and event.get("executable")):
            executables.append(Path(event["executable"]))
    if len(executables) != 1 or not executables[0].is_file():
        raise ValueError("Cargo did not report exactly one built werk host executable")
    return executables[0].resolve()


def validate_profile(profile, output_dir, target):
    if profile == "linux-neutral":
        if sys.platform != "linux" or target is not None:
            raise ValueError("The canonical reference requires a fresh Linux --no-default-features "
                             "build without --target discovery. For packaging use --profile discovery "
                             "and a temporary --output-dir.")
    elif output_dir.resolve() == CANONICAL_OUTPUT.resolve():
        raise ValueError("Noncanonical discovery must use a separate --output-dir; "
                         "it cannot write or check the canonical docs/reference catalogues.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary", type=Path, help="werk binary built from this checkout")
    parser.add_argument("--target", help="artifact's Rust target; cross-builds use a freshly built host tool")
    parser.add_argument("--profile", choices=PROFILES, default="linux-neutral",
                        help="output scope; linux-neutral requires a fresh Linux build without optional features")
    parser.add_argument("--check", action="store_true", help="fail on drift without writing docs")
    parser.add_argument("--output-dir", type=Path, default=CANONICAL_OUTPUT)
    args = parser.parse_args()
    try:
        validate_profile(args.profile, args.output_dir, args.target)
    except ValueError as error:
        parser.error(str(error))
    binary = discovery_binary(args.binary, args.target)
    with tempfile.TemporaryDirectory(prefix="werk-cli-reference-") as store:
        pages, nodes, tasks = generate(binary, Path(store), args.profile)
    task_reference = (ROOT / "docs/reference/tasks-and-formats.md").read_text(encoding="utf-8")
    documented_tasks = set(re.findall(r"^\| `([a-z-]+)` \|", task_reference.split("One manifest", 1)[0], re.M))
    if documented_tasks != set(tasks):
        raise SystemExit("Update tasks-and-formats.md: missing=" + str(sorted(set(tasks) - documented_tasks))
                         + ", obsolete=" + str(sorted(documented_tasks - set(tasks))))
    stale = []
    for name, content in pages.items():
        destination = args.output_dir / name
        if args.check:
            actual = destination.read_text(encoding="utf-8") if destination.exists() else ""
            if actual != content:
                stale.append(name)
                diff = list(difflib.unified_diff(actual.splitlines(), content.splitlines(),
                                                fromfile=name, tofile=name + " (generated)"))
                print("\n".join(diff[:80]))
        else:
            args.output_dir.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8")
    if stale:
        regenerate = [sys.executable, str(Path(__file__).resolve()), str(args.binary),
                      "--profile", args.profile, "--output-dir", str(args.output_dir)]
        if args.target:
            regenerate += ["--target", args.target]
        raise SystemExit("Reference drift: " + ", ".join(stale)
                         + "\nRegenerate after a fresh build from this checkout:\n"
                         + shlex.join(regenerate))
    print(f"{'Checked' if args.check else 'Generated'} {len(pages)} pages: "
          f"{len(nodes)} command/help nodes, {len(tasks)} task schemas.")


if __name__ == "__main__":
    main()
